"""
One database layer for two engines.

    VIGIL_DATABASE_URL set (postgresql://...)  ->  PostgreSQL (Azure Database for PostgreSQL on Azure)
    not set                                     ->  SQLite file in backend/ (local `python run.py`)

The rest of the backend writes SQL once, in the SQLite style it already used:
    ?  and  :name  placeholders, sqlite DDL (INTEGER PRIMARY KEY, STRICT ...), GROUP_CONCAT,
    and two helper functions, days_between(a, b) and vigil_week(timestamp).
For PostgreSQL the placeholders and DDL are translated here, and the helper functions plus a
GROUP_CONCAT aggregate are created in the database (create_postgres_functions), so every query
returns the same results on both engines.

Connections behave like sqlite3's: `with conn:` commits on success and rolls back on error
(it does not close), conn.execute() returns a cursor, and conn.rows() returns a list of dicts.
"""
import atexit
import logging
import os
import re
import sqlite3
import threading
from datetime import datetime
from decimal import Decimal

from utils.path import GUARD_DB

DATABASE_URL = os.environ.get("VIGIL_DATABASE_URL", "").strip()
IS_POSTGRES = DATABASE_URL.startswith(("postgres://", "postgresql://"))

# ___________________ SQL translation for PostgreSQL __________________________

_NAMED_PARAM = re.compile(r"(?<![:\w]):([A-Za-z_]\w*)")   # :name, but not ::cast or 12:30

_DDL = [
    ("INTEGER PRIMARY KEY", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"),
    (") STRICT, WITHOUT ROWID;", ");"),
    (") STRICT;", ");"),
    (" COLLATE NOCASE", ""),
    (" CHECK (json_valid(reasons))", ""),
]


def to_postgres(sql):
    """Rewrite SQLite-style SQL for psycopg: escape %, ? -> %s, :name -> %(name)s, sqlite-only DDL."""
    for old, new in _DDL:
        sql = sql.replace(old, new)

    sql = sql.replace("%", "%%")
    sql = _NAMED_PARAM.sub(r"%(\1)s", sql)
    return sql.replace("?", "%s")


POSTGRES_FUNCTIONS = r'''
CREATE OR REPLACE FUNCTION days_between(a text, b text) RETURNS integer LANGUAGE sql STABLE AS $$
    SELECT CASE WHEN a IS NULL OR b IS NULL THEN NULL
                ELSE trunc(extract(epoch FROM (a::timestamptz - b::timestamptz)) / 86400)::integer END
$$;

CREATE OR REPLACE FUNCTION vigil_week(t text) RETURNS text LANGUAGE sql STABLE AS $$
    SELECT to_char(date_trunc('week', (t::timestamptz) AT TIME ZONE 'UTC'), 'YYYY-MM-DD')
$$;

CREATE OR REPLACE FUNCTION vigil_concat(acc text, val text, sep text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE WHEN val IS NULL THEN acc WHEN acc IS NULL THEN val ELSE acc || sep || val END
$$;

CREATE OR REPLACE FUNCTION vigil_concat(acc text, val text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
    SELECT vigil_concat(acc, val, ',')
$$;

CREATE OR REPLACE AGGREGATE group_concat(text, text) (SFUNC = vigil_concat, STYPE = text);
CREATE OR REPLACE AGGREGATE group_concat(text) (SFUNC = vigil_concat, STYPE = text);
'''


# ___________________ SQLite helper functions (same results as the PostgreSQL ones) ____

def _days_between(a, b):
    if a is None or b is None:
        return None

    return int((datetime.fromisoformat(a.replace("Z", "+00:00")) - datetime.fromisoformat(b.replace("Z", "+00:00")))
               .total_seconds() / 86400)


def _vigil_week(value):
    if value is None:
        return None

    day = datetime.fromisoformat(value[:10])
    return datetime.fromordinal(day.toordinal() - day.weekday()).strftime("%Y-%m-%d")


# ___________________ Connection wrapper ______________________________________

def _clean(value):
    """PostgreSQL returns Decimal for AVG/ROUND; the API wants plain numbers."""
    if isinstance(value, Decimal):
        return int(value) if value == value.to_integral_value() else float(value)

    return value


class Cursor:
    def __init__(self, raw):
        self._raw = raw

    def execute(self, sql, params=()):
        if IS_POSTGRES:
            self._raw.execute(to_postgres(sql), params)
        else:
            self._raw.execute(sql, params)
        return self

    def executemany(self, sql, seq):
        self._raw.executemany(to_postgres(sql) if IS_POSTGRES else sql, seq)
        return self

    def fetchone(self):
        return self._raw.fetchone()

    def fetchall(self):
        return self._raw.fetchall()

    def __iter__(self):
        return iter(self._raw.fetchall())

    @property
    def rowcount(self):
        return self._raw.rowcount

    @property
    def description(self):
        return self._raw.description


class Connection:
    def __init__(self, raw, pool=None):
        self._raw = raw
        self._pool = pool   # PostgreSQL: close() hands the connection back to the pool

    def cursor(self):
        return Cursor(self._raw.cursor())

    def execute(self, sql, params=()):
        if IS_POSTGRES and sql.lstrip().upper().startswith("PRAGMA"):
            return Cursor(self._raw.cursor())          # SQLite-only setting, nothing to do
        return self.cursor().execute(sql, params)

    def executemany(self, sql, seq):
        return self.cursor().executemany(sql, seq)

    def executescript(self, script):
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)

    def rows(self, sql, params=()):
        cursor = self.execute(sql, params)
        columns = [column[0] for column in cursor.description]
        return [{key: _clean(value) for key, value in zip(columns, row)} for row in cursor.fetchall()]

    def commit(self):
        self._raw.commit()

    def rollback(self):
        self._raw.rollback()

    def close(self):
        if self._raw is None:
            return

        if self._pool is None:
            self._raw.close()
        else:
            # Readers never commit: end their transaction here so the pool gets a clean connection back
            if self._raw.info.transaction_status != 0:   # 0 = IDLE
                self._raw.rollback()
            self._pool.putconn(self._raw)

        self._raw = None

    # sqlite3 semantics: commit or roll back, keep the connection open
    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, traceback):
        if exc_type is None:
            self.commit()
        else:
            self.rollback()
        return False


# ___________________ PostgreSQL connection pool ______________________________
# Opening a PostgreSQL connection costs a TLS handshake and a login, several network round trips,
# and on Azure the API and database are in different regions. The dashboard's summary alone runs a
# dozen queries, so connections are opened once and reused.

_pool = None
_pool_lock = threading.Lock()

POOL_MIN = int(os.environ.get("VIGIL_DB_POOL_MIN", "1"))
POOL_MAX = int(os.environ.get("VIGIL_DB_POOL_MAX", "8"))


def get_pool():
    global _pool

    if _pool is None:
        with _pool_lock:
            if _pool is None:
                from psycopg_pool import ConnectionPool   # only needed on Azure

                _pool = ConnectionPool(
                    DATABASE_URL,
                    min_size=POOL_MIN,
                    max_size=POOL_MAX,
                    kwargs={"connect_timeout": 15},
                    check=ConnectionPool.check_connection,   # drop connections the server closed while idle
                    max_idle=300,
                    name="vigil",
                    open=True,
                )
                atexit.register(close_pool)   # scripts exit cleanly; the API also closes it on shutdown
    return _pool


def close_pool():
    """Close every pooled connection (app shutdown)."""
    global _pool

    with _pool_lock:
        if _pool is not None:
            _pool.close()
            _pool = None


def connect_db(db_path=GUARD_DB):
    """Open the identity database: PostgreSQL when VIGIL_DATABASE_URL is set, otherwise the SQLite file.
    Always close() the result: on PostgreSQL that returns the connection to the pool."""
    if IS_POSTGRES:
        pool = get_pool()
        return Connection(pool.getconn(timeout=30), pool)

    try:
        raw = sqlite3.connect(db_path)
    except Exception as error:
        logging.error(f"Failed to connect to the database :{error}")
        raise

    raw.create_function("days_between", 2, _days_between, deterministic=True)
    raw.create_function("vigil_week", 1, _vigil_week, deterministic=True)
    return Connection(raw)


def create_postgres_functions(conn):
    """Install days_between, vigil_week and GROUP_CONCAT in PostgreSQL (no-op on SQLite)."""
    if IS_POSTGRES:
        # Sent as-is: the $$ bodies must not go through placeholder translation
        conn._raw.execute(POSTGRES_FUNCTIONS)
